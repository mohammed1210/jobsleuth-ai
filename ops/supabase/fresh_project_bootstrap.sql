-- REVIEW CANDIDATE ONLY: fresh, empty JobSleuth project.
-- Do NOT apply to PropNexus or an existing database. No user migration is performed.
-- This matches the current backend's bigint job IDs, not the incompatible
-- 2024 historical UUID-job migration.
begin;
set local lock_timeout = '5s';

do $preflight$
begin
  if exists (
    select 1 from pg_catalog.pg_tables
    where schemaname = 'public'
      and tablename in ('jobs','user_profiles','saved_jobs','subscriptions',
                        'evidence_cards','pilot_feedback')
  ) then
    raise exception 'Fresh-project bootstrap refused: application tables already exist';
  end if;
end
$preflight$;

create extension if not exists pgcrypto;

create table public.jobs (
  id bigint generated by default as identity primary key,
  title text not null,
  company text not null,
  location text not null,
  salary text,
  salary_min integer,
  salary_max integer,
  role_type text,
  source text,
  url text,
  description text,
  created_at timestamptz not null default now()
);
create index jobs_location_idx on public.jobs(location);
create index jobs_role_type_idx on public.jobs(role_type);
create index jobs_created_at_idx on public.jobs(created_at desc);

create table public.user_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text,
  full_name text,
  desired_title text,
  location text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.saved_jobs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  job_id bigint not null references public.jobs(id) on delete cascade,
  saved_at timestamptz not null default now(),
  unique (user_id, job_id)
);
create index saved_jobs_user_id_idx on public.saved_jobs(user_id);
create index saved_jobs_job_id_idx on public.saved_jobs(job_id);

-- This is the current main-branch subscriptions shape. The unmerged PR #90
-- adds atomic revision fields and its RPC in a separate approved migration.
create table public.subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade,
  stripe_customer_id text unique,
  stripe_subscription_id text unique,
  plan text not null default 'free',
  status text not null default 'inactive',
  current_period_end timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index subscriptions_user_id_idx on public.subscriptions(user_id);

create table public.evidence_cards (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  situation text not null default '',
  task text not null default '',
  actions jsonb not null default '[]'::jsonb,
  outcome text not null default '',
  reflection text not null default '',
  tags text[] not null default '{}',
  behaviours text[] not null default '{}',
  skills text[] not null default '{}',
  authority_context text,
  source text not null default 'manual',
  confidence integer not null default 70 check (confidence between 0 and 100),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index evidence_cards_user_id_idx on public.evidence_cards(user_id);
create index evidence_cards_updated_at_idx on public.evidence_cards(updated_at desc);

create table public.pilot_feedback (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  provider text not null default '',
  recommendation text not null default '',
  application_type text not null default '',
  word_count integer not null default 0 check (word_count >= 0),
  usefulness integer check (usefulness between 1 and 10),
  would_submit boolean,
  recommendation_trust boolean,
  material_time_saving boolean,
  would_use_again boolean,
  payment_signal text check (payment_signal in ('yes','maybe','no')),
  created_at timestamptz not null default now()
);
create index pilot_feedback_user_id_idx on public.pilot_feedback(user_id);
create index pilot_feedback_created_at_idx on public.pilot_feedback(created_at desc);

-- Explicit RLS and least-privilege grants: no publicly visible customer tables.
alter table public.jobs enable row level security;
alter table public.user_profiles enable row level security;
alter table public.saved_jobs enable row level security;
alter table public.subscriptions enable row level security;
alter table public.evidence_cards enable row level security;
alter table public.pilot_feedback enable row level security;

create policy "Public jobs read" on public.jobs
  for select to anon, authenticated using (true);
create policy "Profile owner read" on public.user_profiles
  for select to authenticated using ((select auth.uid()) = user_id);
create policy "Profile owner insert" on public.user_profiles
  for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "Profile owner update" on public.user_profiles
  for update to authenticated using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
create policy "Saved jobs owner read" on public.saved_jobs
  for select to authenticated using ((select auth.uid()) = user_id);
create policy "Saved jobs owner insert" on public.saved_jobs
  for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "Saved jobs owner delete" on public.saved_jobs
  for delete to authenticated using ((select auth.uid()) = user_id);
create policy "Subscriptions owner read" on public.subscriptions
  for select to authenticated using ((select auth.uid()) = user_id);
create policy "Evidence owner read" on public.evidence_cards
  for select to authenticated using ((select auth.uid()) = user_id);
create policy "Evidence owner insert" on public.evidence_cards
  for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "Evidence owner update" on public.evidence_cards
  for update to authenticated using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
create policy "Evidence owner delete" on public.evidence_cards
  for delete to authenticated using ((select auth.uid()) = user_id);
create policy "Pilot feedback owner read" on public.pilot_feedback
  for select to authenticated using ((select auth.uid()) = user_id);
create policy "Pilot feedback owner insert" on public.pilot_feedback
  for insert to authenticated with check ((select auth.uid()) = user_id);

grant usage on schema public to anon, authenticated, service_role;
revoke all on table public.jobs, public.user_profiles, public.saved_jobs,
  public.subscriptions, public.evidence_cards, public.pilot_feedback
  from public, anon, authenticated;
grant select on table public.jobs to anon, authenticated;
grant select, insert, update on table public.user_profiles to authenticated;
grant select, insert, delete on table public.saved_jobs to authenticated;
grant select on table public.subscriptions to authenticated;
grant select, insert, update, delete on table public.evidence_cards to authenticated;
grant select, insert on table public.pilot_feedback to authenticated;
grant select, insert, update, delete on table public.jobs, public.user_profiles,
  public.saved_jobs, public.subscriptions, public.evidence_cards,
  public.pilot_feedback to service_role;
revoke all on sequence public.jobs_id_seq, public.saved_jobs_id_seq,
  public.subscriptions_id_seq from public, anon, authenticated;
grant usage, select on sequence public.saved_jobs_id_seq to authenticated;
grant usage, select on sequence public.jobs_id_seq, public.saved_jobs_id_seq,
  public.subscriptions_id_seq to service_role;

-- Supabase's automatic-RLS event-trigger function needs no direct API access.
-- It will remain available to its internal event trigger after this revocation.
do $function_acl$
begin
  if to_regprocedure('public.rls_auto_enable()') is not null then
    execute 'revoke execute on function public.rls_auto_enable() from public, anon, authenticated';
  end if;
end
$function_acl$;
commit;
